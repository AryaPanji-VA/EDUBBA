// Deterministic curriculum apply-SQL generator.
// Never applied automatically: the developer reviews and runs the generated
// SQL manually in the Supabase SQL Editor. Safety model:
//   1. The incoming manifest must validate (fail-closed).
//   2. Any CONFLICT against the snapshot refuses generation entirely —
//      existing curriculum (especially the mature Programming course) is
//      never silently overwritten.
//   3. Only ADD entries generate statements; every statement is an
//      idempotent insert with ON CONFLICT DO NOTHING (plus the same
//      null-safe semester placement UPDATE pattern used by
//      database/phase13-semesters.sql).
// The generator is data-only: it never emits DDL, DROP, DELETE, or TRUNCATE,
// and it never touches progress, mastery, learning logs, or Robin memory.

import type { CurriculumManifest } from "@/data/curriculum-manifest";
import { validateCurriculumManifest, type CurriculumValidationError } from "./validation";
import { diffCurriculumManifest, type CurriculumDiffEntry } from "./diff";

export type CurriculumApplySqlResult =
  | {
      ok: true;
      sql: string;
      planned: { semesters: number; courses: number; modules: number; lessons: number };
      unchanged: number;
      missing: number;
    }
  | { ok: false; reason: "invalid"; errors: CurriculumValidationError[] }
  | { ok: false; reason: "conflicts"; conflicts: CurriculumDiffEntry[] };

function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function sqlText(value: string | undefined): string {
  return value === undefined ? "null::text" : sqlString(value);
}

export function generateCurriculumApplySql(incoming: unknown, snapshot: CurriculumManifest): CurriculumApplySqlResult {
  const validation = validateCurriculumManifest(incoming);
  if (!validation.ok) return { ok: false, reason: "invalid", errors: validation.errors };

  const diff = diffCurriculumManifest(validation.manifest, snapshot);
  const conflicts = diff.entries.filter((entry) => entry.status === "conflict");
  if (conflicts.length > 0) {
    return { ok: false, reason: "conflicts", conflicts };
  }

  const addSemesters = diff.entries.filter((entry): entry is CurriculumDiffEntry & { semesterNumber: number } =>
    entry.status === "add" && entry.kind === "semester" && entry.semesterNumber !== null);
  const addCourses = diff.entries.filter((entry): entry is CurriculumDiffEntry & { courseSlug: string; semesterNumber: number } =>
    entry.status === "add" && entry.kind === "course" && entry.courseSlug !== null && entry.semesterNumber !== null);
  const addModules = diff.entries.filter((entry): entry is CurriculumDiffEntry & { courseSlug: string; moduleSlug: string } =>
    entry.status === "add" && entry.kind === "module" && entry.courseSlug !== null && entry.moduleSlug !== null);
  const addLessons = diff.entries.filter((entry): entry is CurriculumDiffEntry & { courseSlug: string; moduleSlug: string; lessonSlug: string } =>
    entry.status === "add" && entry.kind === "lesson" && entry.courseSlug !== null && entry.moduleSlug !== null && entry.lessonSlug !== null);

  const planned = {
    semesters: addSemesters.length,
    courses: addCourses.length,
    modules: addModules.length,
    lessons: addLessons.length,
  };

  const manifest = validation.manifest;
  const lines: string[] = [];
  lines.push("begin;");
  lines.push("");
  lines.push("-- Curriculum apply SQL generated by lib/curriculum/apply-sql.ts.");
  lines.push("-- REVIEW BEFORE RUNNING in the Supabase SQL Editor. ROBIN never applies this automatically.");
  lines.push("-- Adds only: existing rows are never updated or deleted (ON CONFLICT DO NOTHING).");
  lines.push(`-- Planned: ${planned.semesters} semesters, ${planned.courses} courses, ${planned.modules} modules, ${planned.lessons} lessons.`);
  lines.push("");

  if (planned.semesters === 0 && planned.courses === 0 && planned.modules === 0 && planned.lessons === 0) {
    lines.push("-- Nothing to add: every entry is unchanged or informational-only.");
    lines.push("");
  }

  if (planned.semesters > 0) {
    lines.push("-- New semester shells");
    for (const entry of addSemesters) {
      const semester = manifest.semesters.find((item) => item.number === entry.semesterNumber);
      if (semester) {
        lines.push(`insert into public.semesters (number, title) values (${semester.number}, ${sqlString(semester.title)}) on conflict (number) do nothing;`);
      }
    }
    lines.push("");
  }

  if (planned.courses > 0) {
    lines.push("-- New courses");
    lines.push("insert into public.courses (slug, title, description, total_lessons) values");
    const rows: string[] = [];
    for (const entry of addCourses) {
      const course = manifest.semesters
        .flatMap((semester) => semester.courses)
        .find((item) => item.slug === entry.courseSlug);
      if (course) {
        rows.push(`  (${sqlString(course.slug)}, ${sqlString(course.title)}, ${sqlString(course.description)}, ${course.totalLessons ?? 0})`);
      }
    }
    lines.push(rows.join(",\n") + " on conflict (slug) do nothing;");
    lines.push("");
    lines.push("-- Semester placement for new courses (null-safe, never moves a placed course)");
    const bySemester = new Map<number, string[]>();
    for (const entry of addCourses) {
      const slugs = bySemester.get(entry.semesterNumber) ?? [];
      slugs.push(entry.courseSlug);
      bySemester.set(entry.semesterNumber, slugs);
    }
    for (const [semesterNumber, slugs] of [...bySemester.entries()].sort((a, b) => a[0] - b[0])) {
      lines.push(`update public.courses set semester_id = (select id from public.semesters where number = ${semesterNumber})`);
      lines.push(`where slug in (${slugs.map(sqlString).join(", ")}) and semester_id is null;`);
    }
    lines.push("");
  }

  if (planned.modules > 0) {
    lines.push("-- New modules");
    for (const entry of addModules) {
      const course = manifest.semesters
        .flatMap((semester) => semester.courses)
        .find((item) => item.slug === entry.courseSlug);
      const courseModule = course?.modules.find((item) => item.slug === entry.moduleSlug);
      if (course && courseModule) {
        lines.push(`insert into public.modules (course_id, slug, title, description, position)`);
        lines.push(`select c.id, v.slug, v.title, v.description, v.position`);
        lines.push(`from public.courses c`);
        lines.push(`cross join (values (${sqlString(courseModule.slug)}, ${sqlString(courseModule.title)}, ${sqlText(courseModule.description)}, ${courseModule.position})) as v(slug, title, description, position)`);
        lines.push(`where c.slug = ${sqlString(course.slug)} on conflict (course_id, slug) do nothing;`);
        lines.push("");
      }
    }
  }

  if (planned.lessons > 0) {
    lines.push("-- New lessons");
    for (const entry of addLessons) {
      const course = manifest.semesters
        .flatMap((semester) => semester.courses)
        .find((item) => item.slug === entry.courseSlug);
      const courseModule = course?.modules.find((item) => item.slug === entry.moduleSlug);
      const lesson = courseModule?.lessons.find((item) => item.slug === entry.lessonSlug);
      if (course && courseModule && lesson) {
        lines.push(`insert into public.lessons (module_id, slug, title, summary, estimated_minutes, position)`);
        lines.push(`select mo.id, v.slug, v.title, v.summary, v.estimated_minutes, v.position`);
        lines.push(`from public.courses c`);
        lines.push(`join public.modules mo on mo.course_id = c.id`);
        lines.push(`cross join (values (${sqlString(lesson.slug)}, ${sqlString(lesson.title)}, ${sqlText(lesson.summary)}, ${lesson.estimatedMinutes ?? 10}, ${lesson.position})) as v(slug, title, summary, estimated_minutes, position)`);
        lines.push(`where c.slug = ${sqlString(course.slug)} and mo.slug = ${sqlString(courseModule.slug)} on conflict (module_id, slug) do nothing;`);
        lines.push("");
      }
    }
  }

  lines.push("commit;");
  lines.push("");

  return {
    ok: true,
    sql: lines.join("\n"),
    planned,
    unchanged: diff.summary.unchanged,
    missing: diff.summary.missing,
  };
}
